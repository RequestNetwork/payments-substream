-- Request Network payments: multi-chain physical schema.
-- Physical layout is one Postgres schema per chain (see docs/contract.md); this file holds no
-- schema qualifier because the sink applies it after SET search_path.
--
-- Column formats:
--   timestamp: unix seconds
--   amount, fee_amount, gas_used, gas_price: decimal strings stored as NUMERIC
--   payment_reference: 0x + 64 lowercase hex of topics[1] (already the keccak256 hash of the
--     event's indexed bytes argument, see tron/src/lib.rs L197 -- never hashed again)
--   EVM: contract_address, token_address, from_address, to_address, fee_address and tx_hash are
--     lowercase 0x
--   TRON: addresses are Base58 and tx_hash is hex without 0x (unchanged)
--   log_index: index of the log within the transaction (TRON: tron/src/lib.rs L66 enumerate()
--     order within info.log; EVM: receipt log index within the transaction)
--   energy_used, energy_fee, net_fee: TRON-only, NULL on EVM chains
--   gas_used, gas_price: EVM-only, NULL on TRON
--   inbox_seq: BIGINT per-schema insert cursor (DEFAULT nextval), NULL on rows inserted before
--     it existed, set once, never updated on conflict; an arrival cursor, not a block cursor;
--     gaps are normal. A value is allocated at insert but becomes visible at commit, so while
--     two writers overlap on one schema (e.g. a pool rollout) a lower value can commit after a
--     higher one: readers must not treat max(inbox_seq) as a high-water mark; they advance only
--     up to a transaction-visibility horizon and keep the reference sweep (see docs/contract.md)
--
-- Identity:
--   the physical primary key is `id` (TEXT)
--   TRON id is the legacy key `chain:tx_hash:payment_reference:log_index` (tron/src/lib.rs L113)
--     so imported VM rows and live sink rows upsert in place
--   EVM id is the short key `chain:tx_hash:log_index` (REQ-385)
--   the unique index below is what forbids two id shapes referring to the same log; readers must
--     look up by payment_reference, tx_hash or wallet address, never by id
--
-- evm/schema.sql and tron/schema.sql are generated byte-identical copies of this file
-- (`make sync-schema` in evm/ and tron/, verified by `make check-schema`). Edit this file,
-- never evm/schema.sql or tron/schema.sql directly.

CREATE TABLE IF NOT EXISTS payments (
    id TEXT PRIMARY KEY,
    chain TEXT NOT NULL,
    tx_hash TEXT NOT NULL,
    block_number BIGINT NOT NULL,
    timestamp BIGINT NOT NULL,
    contract_address TEXT NOT NULL,
    token_address TEXT NOT NULL,
    from_address TEXT NOT NULL,
    to_address TEXT NOT NULL,
    amount NUMERIC NOT NULL,
    fee_amount NUMERIC NOT NULL,
    fee_address TEXT NOT NULL,
    payment_reference TEXT NOT NULL,
    energy_used TEXT,
    energy_fee TEXT,
    net_fee TEXT,
    log_index BIGINT NOT NULL DEFAULT 0,
    gas_used NUMERIC,
    gas_price NUMERIC
);

-- CREATE TABLE IF NOT EXISTS skips an already-existing table (the imported TRON table, a reused
-- volume), so columns added after the original 17-column shape are also added idempotently here.
ALTER TABLE payments ADD COLUMN IF NOT EXISTS gas_used NUMERIC;
ALTER TABLE payments ADD COLUMN IF NOT EXISTS gas_price NUMERIC;

-- Insert cursor, REQ-811: arrival order per schema. Two steps so the table is not rewritten;
-- old rows stay NULL. The sink's upsert never lists it, so a replayed row keeps its value.
CREATE SEQUENCE IF NOT EXISTS payments_inbox_seq;
ALTER TABLE payments ADD COLUMN IF NOT EXISTS inbox_seq BIGINT;
ALTER TABLE payments ALTER COLUMN inbox_seq SET DEFAULT nextval('payments_inbox_seq');

-- Indexes for common queries
CREATE INDEX IF NOT EXISTS idx_payments_chain ON payments(chain);
CREATE INDEX IF NOT EXISTS idx_payments_tx_hash ON payments(tx_hash);
CREATE INDEX IF NOT EXISTS idx_payments_block_number ON payments(block_number);
CREATE INDEX IF NOT EXISTS idx_payments_timestamp ON payments(timestamp);
CREATE INDEX IF NOT EXISTS idx_payments_payment_reference ON payments(payment_reference);
CREATE INDEX IF NOT EXISTS idx_payments_from_address ON payments(from_address);
CREATE INDEX IF NOT EXISTS idx_payments_to_address ON payments(to_address);
CREATE INDEX IF NOT EXISTS idx_payments_token_address ON payments(token_address);
CREATE INDEX IF NOT EXISTS idx_payments_chain_block ON payments(chain, block_number);
CREATE UNIQUE INDEX IF NOT EXISTS uq_payments_chain_tx_log ON payments(chain, tx_hash, log_index);
CREATE INDEX IF NOT EXISTS idx_payments_chain_reference ON payments(chain, payment_reference);
CREATE INDEX IF NOT EXISTS idx_payments_inbox_seq ON payments (inbox_seq) WHERE inbox_seq IS NOT NULL;
